const LANG_KEY = 'saifelkady-lang';

function getStoredLang() {
    try {
        return localStorage.getItem(LANG_KEY);
    } catch (e) {
        return null;
    }
}

function storeLang(lang) {
    try {
        localStorage.setItem(LANG_KEY, lang);
    } catch (e) {
        /* ignore */
    }
}

function applyTranslations(lang) {
    const dict = translations[lang] || translations.en;

    document.querySelectorAll('[data-i18n]').forEach((el) => {
        const key = el.getAttribute('data-i18n');
        if (dict[key] !== undefined) {
            el.innerHTML = dict[key];
        }
    });

    document.querySelectorAll('[data-lang-option]').forEach((el) => {
        el.classList.toggle('is-active', el.getAttribute('data-lang-option') === lang);
    });
}

function setLang(lang, { persist = true } = {}) {
    document.documentElement.setAttribute('lang', lang === 'ar' ? 'ar' : 'en');
    document.documentElement.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');
    document.body.classList.toggle('lang-ar', lang === 'ar');

    applyTranslations(lang);

    if (persist) storeLang(lang);
}

function replayIntro() {

    const introLoader = document.getElementById('introLoader');
    document.body.classList.add('is-loading');
    document.body.classList.remove('intro-done');

    if (introLoader) {
        introLoader.classList.remove('is-hidden');
    }
}

function initLang() {
    const stored = getStoredLang();
    const browserLang = (navigator.language || '').toLowerCase().startsWith('ar') ? 'ar' : 'en';
    const initial = stored || browserLang;

    setLang(initial, { persist: false });

    const switchers = [document.getElementById('langSwitch'), document.getElementById('mobileLangSwitch')].filter(Boolean);

    switchers.forEach((btn) => {
        btn.addEventListener('click', () => {
            const current = document.documentElement.getAttribute('lang') === 'ar' ? 'ar' : 'en';
            const next = current === 'ar' ? 'en' : 'ar';

            storeLang(next);
            window.location.reload();
        });
    });
}

document.addEventListener('DOMContentLoaded', initLang);